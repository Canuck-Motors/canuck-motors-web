// "Don’t" and "Don't" are the same key
export const normKey = (s: string) => s.replace(/\s+/g, " ").replace(/[’‘]/g, "'").trim();

const NORM: Map<string, string> = new Map(Object.entries(FR).map(([k, v]) => [normKey(k), v]));

export function lookupFr(text: string): string | null {
  const key = normKey(text);
  const hit = NORM.get(key);
  if (hit != null) return hit;
  for (const [re, fn] of FR_PATTERNS) {
    const m = key.match(re);
    if (m) return fn(...(m as unknown as string[]));
  }
  return null;
}
